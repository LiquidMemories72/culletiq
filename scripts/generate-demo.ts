/**
 * Generates the SYNTHETIC demonstration images in public/demo/ and their manifest.
 * Run: npm run demo:generate
 *
 * Images are drawn procedurally (lib/demo/synthetic.ts) — they are not photographs.
 * Ground truth in the manifest is the drawn pixel area per class, before JPEG encoding.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import jpeg from "jpeg-js";
import { DEMO_SCENES, generateScene } from "../lib/demo/synthetic";
import type { DemoManifest } from "../lib/demo/manifest";
import { REAL_DEMOS } from "../lib/demo/real";

const outDir = path.resolve(__dirname, "..", "public", "demo");
mkdirSync(outDir, { recursive: true });

const manifest: DemoManifest = {
  description:
    "Demonstration images. Items marked synthetic are drawings generated by scripts/generate-demo.ts, not photographs; their ground truth is the drawn pixel area of each glass class, exact for the drawing but saying nothing about performance on real photographs. Items marked real are openly licensed photographs (CC BY-SA 3.0) with no measured ground truth.",
  generatedBy: "scripts/generate-demo.ts",
  encoding: "JPEG quality 92",
  items: [],
};

for (const spec of DEMO_SCENES) {
  const scene = generateScene(spec);
  const file = `${spec.id}.jpg`;
  const encoded = jpeg.encode(
    { width: scene.image.width, height: scene.image.height, data: Buffer.from(scene.image.data.buffer) },
    92,
  );
  writeFileSync(path.join(outDir, file), encoded.data);
  manifest.items.push({
    id: spec.id,
    title: spec.title,
    file,
    synthetic: true,
    description: spec.description,
    limitations: spec.limitations,
    groundTruth: {
      kind: "synthetic-drawn-area",
      percent: scene.groundTruth.glassAreaPercent,
      extraObjects: scene.groundTruth.extraBoxes,
      uncoveredPercentOfImage: scene.groundTruth.uncoveredPercent,
    },
  });
  console.log(`wrote ${file} (${(encoded.data.length / 1024).toFixed(0)} KB)`);
}

// Real photographs (downloaded separately; see public/demo/real/ATTRIBUTION.md). No ground truth.
manifest.items.push(...REAL_DEMOS);

writeFileSync(path.join(outDir, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`wrote manifest.json with ${manifest.items.length} items`);
